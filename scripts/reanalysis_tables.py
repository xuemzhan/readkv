"""Emit LaTeX table bodies for the E3/E4/E7 reanalyses.

Reads the immutable `reports/audit_reanalysis.json` produced by
`scripts.audit_reanalysis` and writes `results_extra.tex` into each paper
directory, so the revised manuscripts never hard-code derived numbers.

Usage:
    python -m scripts.reanalysis_tables
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "reports" / "audit_reanalysis.json"
PAPERS = (
    ROOT / "papers" / "readkv_v2_tmlr_anonymous",
    ROOT / "papers" / "readkv_v2_zh",
)


def ci(x):
    point, lo, hi = x
    return f"{100 * point:.1f}\\,[{100 * lo:.1f},{100 * hi:.1f}]"


def raw_ci(x):
    point, lo, hi = x
    return f"{point:.2f}\\,[{lo:.2f},{hi:.2f}]"


def macro(lines, name, rows):
    lines.append("\\newcommand{\\" + name + "}{%")
    lines.extend(" & ".join(row) + r" \\" for row in rows)
    lines.append("}")


def build(d: dict) -> str:
    lines = ["% Generated by scripts.reanalysis_tables.py from reports/audit_reanalysis.json."]
    e3 = d["E3_controls_equivalence"]
    macro(lines, "ControlTestRows", (
        [str(seed), name,
         raw_ci([c["family_test"]["family_mean_diff"], *c["family_test"]["ci90_family"]]),
         f'{c["family_test"]["two_sided_p"]:.3f}',
         f'{c["family_test"]["tost_p"]:.3f}',
         r"\yes" if c["family_test"]["equivalent_at_delta"] else r"\no"]
        for seed in range(3) for name, c in e3[str(seed)]["controls"].items()
    ))
    macro(lines, "ControlMeanRows", (
        [str(seed), name, raw_ci(c["control_mean_cluster_ci"]), raw_ci(e3[str(seed)]["joint_ecf_cluster"])]
        for seed in range(3) for name, c in e3[str(seed)]["controls"].items()
    ))
    e4 = d["E4_ecf_validity"]
    macro(lines, "ScaleRows", (
        [cell, str(seed), f'{v["mean_abs_dself"]:.2f}', f'{v["mean_joint_ecf"]:.2f}',
         f'{v["ecf_over_abs_dself"]:.2f}']
        for cell in ("A00", "A11") for seed in range(3) for v in [e4["scale"][cell][str(seed)]]
    ))
    macro(lines, "RankRows", (
        [arm, f'{v["spearman_rho"]:+.3f}',
         r"$<10^{-8}$" if v["p"] < 1e-8 else f'{v["p"]:.3f}', str(v["n"])]
        for arm, v in e4["rank_correlation"].items()
    ))
    macro(lines, "MapperGapRows", (
        [str(seed), raw_ci(v["affine_joint_ecf_cluster"]), raw_ci(v["kd_joint_ecf_cluster"]),
         f'{v["affine_dual_joint"]:.3f}', f'{v["kd_dual_joint"]:.3f}']
        for seed in range(3) for v in [e4["mapper_separation"][str(seed)]]
    ))
    e7 = d["E7_extended_sequence_scoring"]
    rows = []
    for seed in range(3):
        for cell in ("A00", "A11"):
            v = e7["per_seed"][str(seed)]["all_60"]
            rows.append([cell, str(seed),
                         ci(v[f"{cell}_first_L"]), ci(v[f"{cell}_full_L"]),
                         ci(v[f"{cell}_length_normalized_L"])])
    macro(lines, "ExtendedScoringRows", rows)
    macro(lines, "ExtendedContrastRows", (
        [str(seed), ci(e7["per_seed"][str(seed)]["all_60"]["contrast_first"]),
         ci(e7["per_seed"][str(seed)]["all_60"]["contrast_full"]),
         ci(e7["per_seed"][str(seed)]["all_60"]["contrast_length_normalized"])]
        for seed in range(3)
    ))
    counts = e7["subsets"]
    macro(lines, "ScoringCountRows", (
        [name.replace("_", r"\_"), cell, str(seed),
         str(counts[name][f"{cell}_{seed}"]["pairs"]),
         str(counts[name][f"{cell}_{seed}"]["families"])]
        for name in counts for cell in ("A00", "A11") for seed in range(3)
    ))
    return "\n".join(lines) + "\n"


def main() -> None:
    d = json.loads(DATA.read_text(encoding="utf-8"))
    text = build(d)
    for paper in PAPERS:
        (paper / "results_extra.tex").write_text(text, encoding="utf-8")
        print(f"Wrote {(paper / 'results_extra.tex').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
