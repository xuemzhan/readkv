"""Export the deterministic counterfactual task dataset used by P1-P5 runs.

The dataset is generated from the frozen builder in
``src/readkv/data/build_cf_pairs.py`` using the sizes in
``configs/protocol.yaml``.  M1/M2/M3 fixes are applied in the builder; this
script only exports and records provenance/hashes/quality into the manifest.
No external download or manual editing is involved.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path

import yaml

from readkv.data.build_cf_pairs import build_cf_pairs, quality_report, save_pairs

ROOT = Path(__file__).resolve().parents[1]
PROTOCOL = ROOT / "configs" / "protocol.yaml"
STATS_CONVENTION = ROOT / "configs" / "prereg" / "stats_convention_v2.3.yaml"
DEFAULT_OUT = ROOT / "data" / "tasks"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _git_head() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
        ).strip()
    except Exception:  # pragma: no cover
        return "unknown"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    protocol = yaml.safe_load(PROTOCOL.read_text(encoding="utf-8"))
    sizes = {k: int(v) for k, v in protocol["data_sizes"].items()}

    pairs = build_cf_pairs(sizes=sizes, seed=args.seed)
    out_dir: Path = args.out_dir
    data_path = save_pairs(pairs, out_dir / "cf_pairs.jsonl")
    report = quality_report(pairs)
    if report["quality_gate"] != "pass":
        raise SystemExit(f"data quality gate failed: {report}")

    manifest = {
        "dataset": "cf_pairs_v2.1",
        "revision": "v2.1-corrected (M1/M2/M3)",
        "description": (
            "Deterministic synthetic F1-F6 counterfactual task pairs. "
            "V2.1: degenerate must_flip pairs eliminated (M1), split-disjoint "
            "entity pools and zero cross-split verbatim overlap (M2), and a "
            "structurally unseen template subset for probe/test (M3)."
        ),
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": "src/readkv/data/build_cf_pairs.py::build_cf_pairs",
        "generator_commit": _git_head(),
        "export_script": "scripts/export_task_data.py",
        "reproduce": "python scripts/export_task_data.py --seed 0",
        "config": str(PROTOCOL.relative_to(ROOT)),
        "config_fingerprint": sha256(PROTOCOL)[:16],
        "stats_convention": {
            "path": str(STATS_CONVENTION.relative_to(ROOT)),
            "version": "2.3",
            "sha256": sha256(STATS_CONVENTION),
            "note": "read-only reference; flip_denominator_excludes=[F5,F6]",
        },
        "protocol_version": protocol["version"],
        "seed": args.seed,
        "sizes": sizes,
        "license": "CC0-1.0 (synthetic data generated by this project; no third-party content)",
        "source": {
            "type": "synthetic",
            "origin": "generated by src/readkv/data/build_cf_pairs.py",
            "external_download": False,
            "external_benchmarks_included": False,
            "note": "All text is template-generated from the project's own entity pools; "
                    "no third-party corpus, no personal data, no license-restricted content.",
        },
        "files": [
            {
                "name": data_path.name,
                "sha256": sha256(data_path),
                "size": data_path.stat().st_size,
                "lines": len(pairs),
            }
        ],
        "quality": report,
        "limitations": [
            "Synthetic, template-generated data; not real-world benchmark data.",
            "real split is empty (M4 pending PI/legal decision); no external anchor.",
            "length_mismatch pairs are all F5 (surface paraphrase) and reported as a separate stratum.",
            "flip denominator excludes F5 and F6 per stats_convention_v2.3.yaml.",
            "unseen-template evidence is structural for test/probe only, still within a synthetic domain.",
        ],
    }
    manifest_path = out_dir / "manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    # manifest 自身哈希 sidecar（manifest 内无法自引用）
    sidecar = out_dir / "manifest.json.sha256"
    sidecar.write_text(f"{sha256(manifest_path)}  manifest.json\n", encoding="utf-8")

    print(f"wrote {data_path} ({len(pairs)} pairs)")
    print(f"wrote {manifest_path}")
    print(f"wrote {sidecar}")


if __name__ == "__main__":
    main()
